const assetRoot = new URL('.', document.currentScript.src);
const languageCodes = {zh:'zh-CN',en:'en',ja:'ja',ru:'ru'};
const fileLanguages = {zh:'中文',en:'English',ja:'日本語',ru:'Русский','zh-ja':'日本語・中国語併記','zh-ru':'Русский / китайский'};
let catalog = [];
function selectedLanguage() {
  const lang = new URL(location.href).searchParams.get('lang') || document.body.dataset.defaultLang || 'zh';
  return Object.hasOwn(translations,lang) ? lang : (document.body.dataset.defaultLang || 'zh');
}
function filesForLanguage(doc,lang) {
  return doc.files.filter(file => file.language===lang || (file.language==='bilingual' && ['zh','en'].includes(lang)) || (file.language==='zh-ja' && lang==='ja') || (file.language==='zh-ru' && lang==='ru'));
}
function render(lang) {
  if (!Object.hasOwn(translations,lang)) lang='zh';
  const t=translations[lang];
  document.documentElement.lang=languageCodes[lang];
  document.title=t.title+' · '+t.center;
  document.querySelector('meta[name=description]').content=t.lead;
  document.querySelectorAll('[data-t]').forEach(el=>{if(t[el.dataset.t]) el.textContent=t[el.dataset.t];});
  document.querySelectorAll('[data-lang]').forEach(el=>el.setAttribute('aria-pressed',String(el.dataset.lang===lang)));
  const holder=document.getElementById('documents');
  holder.setAttribute('aria-label',t.title);
  holder.replaceChildren();
  catalog.forEach((doc,index)=>{
    const card=document.createElement('article'); card.className='document';
    const head=document.createElement('div'); head.className='doc-head';
    const num=document.createElement('span'); num.className='number'; num.textContent=String(index+1).padStart(2,'0');
    const info=document.createElement('div');
    const title=document.createElement('h2'); title.textContent=doc.title[lang];
    const desc=document.createElement('p'); desc.textContent=doc.description[lang];
    info.append(title,desc); head.append(num,info);
    const list=document.createElement('ul'); list.className='file-list';
    filesForLanguage(doc,lang).forEach(file=>{
      const row=document.createElement('li'); row.className='file-row';
      const label=document.createElement('div');
      const name=document.createElement('span'); name.className='file-name';
      name.textContent=file.language==='bilingual'?t.bilingual:fileLanguages[file.language];
      const meta=document.createElement('span'); meta.className='file-meta';
      meta.textContent=`${file.format.toUpperCase()} · ${file.edition || 'V'+file.version} · ${file.pages?file.pages+' '+t.pages+' · ':''}${file.size}`;
      label.append(name,meta);
      const actions=document.createElement('div'); actions.className='actions';
      if(file.format==='pdf'){
        const read=document.createElement('a'); read.href=new URL(file.url,assetRoot).href; read.target='_blank'; read.rel='noopener'; read.className='read'; read.textContent=t.read;
        read.setAttribute('aria-label',`${t.read}: ${doc.title[lang]} (${name.textContent})`); actions.append(read);
      }
      const download=document.createElement('a'); download.href=new URL(file.url,assetRoot).href; download.download=file.downloadName; download.className='download'; download.textContent=file.format==='docx'?t.word:t.download;
      download.setAttribute('aria-label',`${t.download}: ${doc.title[lang]} (${name.textContent}, ${file.format})`); actions.append(download);
      row.append(label,actions); list.append(row);
    });
    card.append(head,list);
    if(doc.id==='application'){
      const note=document.createElement('p'); note.className='note'; note.textContent=t.formNote; card.append(note);
    }
    holder.append(card);
  });
}
